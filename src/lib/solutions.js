// Pick the solution page a project belongs to, from its Contentful tags.
export function solutionForTags(tags = []) {
  const lower = tags.map((t) => t.trim().toLowerCase());
  return SOLUTIONS.find((s) => s.tags.some((t) => lower.includes(t))) || null;
}
